/**
 * Represents the physical condition of a reference material.
 *
 * <p>This enum defines the possible condition levels
 * that can be assigned to a reference material.</p>
 */
public enum ConditionStatus {

    EXCELLENT,
    GOOD,
    FRAGILE,
    DAMAGED,
    RESTORED
}
